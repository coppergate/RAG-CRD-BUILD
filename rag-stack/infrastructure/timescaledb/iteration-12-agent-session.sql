-- Iteration 12: External Agent Session Mapping
--
-- opencode (and any other coding-agent client) identifies a session with an
-- opaque string such as "ses_7f3a9c1b". The rest of the stack keys sessions by
-- BIGINT (sessions.session_id), and contracts.InternalRequest.session_id is an
-- int64. Rather than parsing or hashing the external id, map it.
--
-- Consumed by rag-retrieval (POST /v1/rag/ingest/turn) and, later, by
-- rag-code-gateway. Mirrors common/ent/schema/agent_session.go — ent's
-- Schema.Create() in db-adapter produces the same shape, so the two must agree.

CREATE TABLE IF NOT EXISTS agent_session (
    agent_session_id BIGINT      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    external_id      TEXT        NOT NULL UNIQUE,
    source           TEXT        NOT NULL DEFAULT 'opencode',
    -- source values: opencode | other client ids. Not a DB CHECK, so new
    -- clients can be added without a migration (matches the convention in
    -- iteration-11's status column).
    session_id       BIGINT      NOT NULL REFERENCES sessions(session_id),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The unique constraint on external_id already covers the resolve-or-create
-- lookup; this index serves the reverse direction (all agent sessions for a
-- given RAG session), used when reconstructing session memory.
CREATE INDEX IF NOT EXISTS idx_agent_session_session
    ON agent_session (session_id);

CREATE INDEX IF NOT EXISTS idx_agent_session_last_seen
    ON agent_session (last_seen_at DESC);
