CREATE TABLE IF NOT EXISTS action_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text UNIQUE NOT NULL,
    description text
);
CREATE TABLE IF NOT EXISTS action_identifiers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier text NOT NULL,
    action_type_identifiers bigint NOT NULL REFERENCES action_types(id)
);
CREATE TABLE IF NOT EXISTS behavioral_rules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type text NOT NULL,
    category text,
    state text NOT NULL DEFAULT 'ACTIVE',
    rule_content text NOT NULL,
    priority integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    scope text NOT NULL DEFAULT 'GLOBAL',
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS behavioral_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt_id text NOT NULL,
    rule_id bigint NOT NULL,
    action_type text NOT NULL,
    applied_at timestamp with time zone NOT NULL DEFAULT now(),
    context jsonb
);
CREATE TABLE IF NOT EXISTS session_governances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL,
    rule_id bigint NOT NULL,
    priority_override integer NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    UNIQUE(session_id, rule_id)
);

-- Re-create build tables that I dropped earlier
CREATE TABLE IF NOT EXISTS build_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name text UNIQUE NOT NULL,
    version text NOT NULL,
    last_build timestamp with time zone DEFAULT now() NOT NULL
);
CREATE TABLE IF NOT EXISTS build_locks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name text UNIQUE NOT NULL,
    lock_owner text NOT NULL,
    lock_pid integer NOT NULL,
    lock_host text NOT NULL,
    acquired_at timestamp with time zone DEFAULT now() NOT NULL,
    heartbeat timestamp with time zone DEFAULT now() NOT NULL
);
CREATE TABLE IF NOT EXISTS build_journals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name text UNIQUE NOT NULL,
    last_hash text NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL
);
